/* Одна клітинка: підкладка тіні знизу, зверху — основний колір.
   Саме ця пара і дає «об'ємний піксель», як у краба. */
function cell(ctx, x, y, s, body, shadow, depth) {
  if (shadow) {
    ctx.fillStyle = shadow;
    ctx.fillRect(x, y + depth, s, s);
  }
  ctx.fillStyle = body;
  ctx.fillRect(x, y, s, s);
}

/* Малює рядок символів по GLYPHS. skip — символи, які пропустити
   (двокрапка, коли блимає). */
export function drawGlyphString(ctx, text, opts) {
  const o = opts || {};
  const body = o.body || "#d98263";
  const shadow = o.shadow || null;
  const W = ctx.canvas.width;
  const H = ctx.canvas.height;
  const chars = text.split("");

  let cols = 0;
  for (const ch of chars) {
    const g = GLYPHS[ch];
    if (g) cols += g[0].length + 1;
  }
  cols = Math.max(1, cols - 1);                       // останній проміжок зайвий

  const s = Math.floor(Math.min(W / cols, H / 6));
  const depth = Math.max(2, Math.round(s / 6));
  let x = Math.floor((W - cols * s) / 2);
  const y = Math.floor((H - 5 * s) / 2);

  ctx.clearRect(0, 0, W, H);
  for (const ch of chars) {
    const g = GLYPHS[ch];
    if (!g) continue;
    if (!(o.skip && o.skip.includes(ch))) {
      for (let r = 0; r < g.length; r++) {
        for (let c = 0; c < g[r].length; c++) {
          if (g[r][c] === "1") cell(ctx, x + c * s, y + r * s, s, body, shadow, depth);
        }
      }
    }
    x += (g[0].length + 1) * s;
  }
}

/* Готова іконка як <canvas>. Розмір у клітинках, щоб не було півпікселя.
   Колір беремо з CSS-змінної при створенні: іконки перемальовуються при
   зміні теми (див. repaintIcons у screen.js). */
export function makeIcon(name, cellSize, body, shadow, big) {
  const set = big ? ICONS12 : ICONS;
  const rows = set[name] || ICONS[name] || ICONS12[name];
  const canvas = document.createElement("canvas");
  canvas.className = "pxicon";
  const s = Math.max(1, Math.round(cellSize));
  const depth = Math.max(1, Math.round(s / 5));
  const cols = rows ? rows[0].length : 7;
  canvas.width = cols * s;
  canvas.height = (rows ? rows.length : 7) * s + depth;
  canvas.dataset.icon = name;
  canvas.dataset.big = big ? "1" : "";
  if (!rows) return canvas;

  const ctx = canvas.getContext("2d");
  for (let r = 0; r < rows.length; r++) {
    for (let c = 0; c < rows[r].length; c++) {
      if (rows[r][c] === "1") cell(ctx, c * s, r * s, s, body, shadow, depth);
    }
  }
  return canvas;
}

/* Перемалювати вже вставлену іконку іншим кольором (зміна теми/стану) */
export function paintIcon(canvas, body, shadow) {
  const name = canvas.dataset.icon;
  const rows = canvas.dataset.big ? (ICONS12[name] || ICONS[name]) : (ICONS[name] || ICONS12[name]);
  if (!rows) return;
  const s = Math.round(canvas.width / rows[0].length);
  const depth = Math.max(1, Math.round(s / 5));
  const ctx = canvas.getContext("2d");
  ctx.clearRect(0, 0, canvas.width, canvas.height);
  for (let r = 0; r < rows.length; r++) {
    for (let c = 0; c < rows[r].length; c++) {
      if (rows[r][c] === "1") cell(ctx, c * s, r * s, s, body, shadow, depth);
    }
  }
}
