# Слово з латиниці: літери плюс внутрішні дефіс/апостроф (wi-fi, don't).
_WORD_RE = re.compile(r"[A-Za-z]+(?:[-'’][A-Za-z]+)*")


def _spell(word: str) -> str:
    """
    Абревіатура по літерах: GPIO → «джі пі ай о».

    Роздільник саме ПРОБІЛ, не дефіс. Заміряно round-trip через Whisper:
    «джі-пі-ай-о» Piper вимовляє злитою кашею (розпізнається як «GP-BYO»),
    а «джі пі ай о» — чисто, назад як «GPIO».
    """
    return " ".join(LETTERS.get(ch, ch) for ch in word.lower() if ch.isalpha())


def _translit(word: str) -> str:
    """Побуквенна транслітерація з диграфами — остання лінія оборони."""
    low = word.lower()
    out: list[str] = []
    i = 0
    while i < len(low):
        for src, dst in DIGRAPHS:
            if low.startswith(src, i):
                out.append(dst)
                i += len(src)
                break
        else:
            ch = low[i]
            out.append(SINGLE.get(ch, "" if ch in "-'’" else ch))
            i += 1
    return "".join(out)


def _word(word: str) -> str:
    """Одне латинське слово → кирилиця (словник → абревіатура → транслітерація)."""
    low = word.lower()
    if low in KNOWN:
        return KNOWN[low]
    # Абревіатура: усі літери великі, 2–5 знаків (GPIO, API, USB, SSD).
    letters = [c for c in word if c.isalpha()]
    if 2 <= len(letters) <= 5 and all(c.isupper() for c in letters):
        return _spell(word)
    return _translit(word)


def adapt(text: str) -> str:
    """
    Переписує латиницю в тексті кирилицею для українського TTS.

    Кирилиця, цифри й пунктуація не змінюються — чіпаємо ЛИШЕ латинські слова.
    Викликати ДО переведення в нижній регістр: правило абревіатур залежить
    від того, що слово написане великими літерами.
    """
    if not text:
        return text

    # Спершу — багатослівні записи зі словника («raspberry pi» як ціле),
    # інакше «pi» окремим словом дало б «респбері пай» → «респбері» + «пай»
    # лише випадково; для інших пар (напр. «wi fi») збіг би взагалі зник.
    for phrase in sorted((k for k in KNOWN if " " in k), key=len, reverse=True):
        text = re.sub(
            r"(?<![A-Za-z])" + re.escape(phrase) + r"(?![A-Za-z])",
            KNOWN[phrase],
            text,
            flags=re.IGNORECASE,
        )

    return _WORD_RE.sub(lambda m: _word(m.group(0)), text)
