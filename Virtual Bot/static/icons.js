/* Іконка як DOM-вузол. Розмір і товщину дає CSS-клас (за замовчуванням .ico),
   тому один і той самий шлях працює і в дрібній вкладці, і у великій кнопці. */
function iconEl(name, className) {
  const path = ICON_PATHS[name];
  const svg = document.createElementNS("http://www.w3.org/2000/svg", "svg");
  svg.setAttribute("viewBox", "0 0 24 24");
  svg.setAttribute("aria-hidden", "true");
  svg.setAttribute("class", className || "ico");
  // innerHTML на SVG-елементі коректно парсить дочірні шляхи в усіх сучасних
  // браузерах; рядки — наші власні константи, не користувацький ввід.
  svg.innerHTML = path || "";
  return svg;
}

/* Іконка як рядок розмітки — для місць, де вже будується HTML-рядок. */
function iconHTML(name, className) {
  const path = ICON_PATHS[name];
  if (!path) return "";
  return (
    '<svg viewBox="0 0 24 24" aria-hidden="true" class="' +
    (className || "ico") +
    '">' + path + "</svg>"
  );
}

/* Іконка + текст в одному рядку: типовий вміст кнопки. Текст іде окремим
   <span>, щоб іконка не з'їжджала за багаторядкового підпису. */
function iconLabel(name, text, className) {
  const frag = document.createDocumentFragment();
  frag.appendChild(iconEl(name, className));
  const span = document.createElement("span");
  span.textContent = text;
  frag.appendChild(span);
  return frag;
}

window.Icons = { paths: ICON_PATHS, el: iconEl, html: iconHTML, label: iconLabel };
