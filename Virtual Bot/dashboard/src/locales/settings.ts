export type SettingsKey = keyof typeof uk;

export function t(key: SettingsKey, values: Record<string, string | number> = {}): string {
  const locale = typeof document !== 'undefined' && document.documentElement.lang.startsWith('en') ? en : uk;
  return locale[key].replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match));
}

export function groupLabel(id: string): string {
  const key = `settings.group.${id}` as SettingsKey;
  if (!(key in uk)) return id;
  return t(key);
}

export function ocText(path: string, hint = false): string {
  const key = `settings.oc.${path}${hint ? '.hint' : ''}` as SettingsKey;
  if (!(key in uk)) return hint ? '' : path;
  return t(key);
}

export function settingsMatch(query: string): boolean {
  const needle = query.trim().toLowerCase();
  if (!needle) return true;
  const table = typeof document !== 'undefined' && document.documentElement.lang.startsWith('en') ? en : uk;
  return Object.entries(table).some(
    ([key, value]) => key.startsWith('settings.oc.') && value.toLowerCase().includes(needle),
  );
}
