"""
«Клод Бот» — канонічні назви моделей у розпізнаному тексті.

Дзеркало до [voice_latin.py]: той переписує латиницю кирилицею ПЕРЕД синтезом,
а цей — навпаки, повертає кирилиці з мікрофона канонічне написання ПІСЛЯ
розпізнавання. Потрібно з двох причин:

1) одну модель кажуть по-різному («джемінай» і «геміні»), а бот мусить бачити
   одне слово — інакше кожна вимова це окремий термін;
2) назви моделей у config.yaml латиницею (`opencode-go/qwen3.7-max`), тож
   «кван» з мікрофона мозок ні з чим не звіряє, а «Qwen» — звіряє.

`asr.hotwords` і цей модуль вирішують РІЗНІ половини задачі: підказки впливають
на те, що модель почує, аліаси — на те, як це записано. Заміряно: підказки
самі витягують багатоскладові назви («джемінай», «кімі», «ГЛМ»), але короткі
однослівні не витягують — «Квен» стабільно чується як «кван» і з підказками,
і без них. Саме такі випадки й ловить заміна за списком.

Латиницю в `asr.hotwords` НЕ кладемо: заміряно, що вона тягне за собою сусідні
українські слова («про це» → «Proceek», «ГЛМ» → «G, L, M»). Підказки лишаються
кирилицею, канонізує вже цей модуль.
"""

from __future__ import annotations

import re

import app_config as cfg


def _compile(aliases: dict[str, list[str]]) -> list[tuple[re.Pattern[str], str]]:
    """
    Готує пари (регулярка, канон). Довші варіанти йдуть ПЕРШИМИ: інакше «ге ел
    ем» ніколи б не збіглося, бо однослівне «ем» встигло б розірвати фразу.

    Межі слова — `(?<!\\w)`/`(?!\\w)`, а не `\\b`: кириличні літери для `re`
    теж `\\w`, тож звичайні межі тут працюють, а от дефіс і цифра поруч ні —
    і саме так Whisper віддає «ГЛМ-5-3» та «клод-код».
    """
    out: list[tuple[re.Pattern[str], str]] = []
    for canonical, variants in aliases.items():
        for variant in sorted(variants, key=len, reverse=True):
            pattern = re.compile(
                r"(?<!\w)" + re.escape(variant) + r"(?!\w)",
                flags=re.IGNORECASE | re.UNICODE,
            )
            out.append((pattern, canonical))
    out.sort(key=lambda pair: len(pair[0].pattern), reverse=True)
    return out


_RULES = _compile(cfg.ASR_ALIASES)


def rules_count() -> int:
    """Скільки варіантів написання ми знаємо (для діагностики)."""
    return len(_RULES)


def normalize(text: str) -> str:
    """
    Замінює відомі вимови назв на канонічне написання.

    Форми слова НЕ відмінюємо: збіг лише точний, тому «Джемінаєм» лишиться як
    почулось. Це навмисно — предбачувано й без здогадок; потрібну відмінкову
    форму просто додають у `asr.aliases` окремим варіантом.
    """
    if not text or not _RULES:
        return text
    for pattern, canonical in _RULES:
        text = pattern.sub(canonical, text)
    return text
